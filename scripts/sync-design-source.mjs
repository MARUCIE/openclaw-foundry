import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const UPSTREAM = {
  owner: 'material-components',
  repo: 'material-components-web',
  commit: '6ceadb81df508ac08ab007c52c4d3dc1d811cc15',
  files: [
    'packages/mdc-layout-grid/README.md',
    'packages/mdc-layout-grid/_variables.scss',
    'packages/mdc-layout-grid/mdc-layout-grid.scss',
  ],
};

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const outputPath = path.join(repoRoot, 'design.md');
const lockPath = path.join(repoRoot, 'design.source.lock.json');

function rawUrl(filePath) {
  return `https://raw.githubusercontent.com/${UPSTREAM.owner}/${UPSTREAM.repo}/${UPSTREAM.commit}/${filePath}`;
}

async function fetchText(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`);
  }
  return response.text();
}

function fenceFor(filePath) {
  if (filePath.endsWith('.md')) return 'md';
  if (filePath.endsWith('.scss')) return 'scss';
  return 'txt';
}

function wrapVendoredContent(filePath, content) {
  const language = fenceFor(filePath);
  return `\`\`\`\`${language}\n${content.trimEnd()}\n\`\`\`\``;
}

function sha256(text) {
  return createHash('sha256').update(text).digest('hex');
}

function isSha256(value) {
  return typeof value === 'string' && /^[a-f0-9]{64}$/.test(value);
}

function expectedLockMetadata() {
  return UPSTREAM.files.map((filePath) => ({
    path: filePath,
    url: rawUrl(filePath),
  }));
}

function validateLock(lock) {
  if (!lock || typeof lock !== 'object') {
    throw new Error(`design.source.lock.json is invalid. Run: npm run design:sync-source`);
  }
  if (JSON.stringify(lock.upstream) !== JSON.stringify(UPSTREAM)) {
    throw new Error(`design.source.lock.json does not match the pinned upstream config. Run: npm run design:sync-source`);
  }
  if (!lock.document || lock.document.path !== 'design.md' || !isSha256(lock.document.sha256)) {
    throw new Error(`design.source.lock.json has an invalid document record. Run: npm run design:sync-source`);
  }
  if (!Array.isArray(lock.files) || lock.files.length !== UPSTREAM.files.length) {
    throw new Error(`design.source.lock.json has an invalid file list. Run: npm run design:sync-source`);
  }

  const expected = expectedLockMetadata();
  for (const [index, item] of lock.files.entries()) {
    const expectedItem = expected[index];
    if (!item || item.path !== expectedItem.path || item.url !== expectedItem.url || !isSha256(item.sha256)) {
      throw new Error(`design.source.lock.json has an invalid upstream file record. Run: npm run design:sync-source`);
    }
  }
}

function buildDocument(fetched) {
  return `# Vendored Material Web Layout Grid Reference

<!-- AUTO-GENERATED FILE: do not edit manually. Run \`npm run design:sync-source\`. -->

## Provenance

This file is generated by pulling upstream source files from the official Google-authored Material Components Web GitHub repository.

- repository: \`${UPSTREAM.owner}/${UPSTREAM.repo}\`
- upstream commit: \`${UPSTREAM.commit}\`
- generator: \`scripts/sync-design-source.mjs\`

Canonical upstream URLs:

${fetched.map(({ filePath, url }) => `- \`${url}\``).join('\n')}

## Vendored Upstream Files

${fetched.map(({ filePath, content, url }) => `### \`${filePath}\`\n\nSource: \`${url}\`\n\n${wrapVendoredContent(filePath, content)}`).join('\n\n')}

## Local Repository Adapter

This repository does not use Material Web components directly for its standalone HTML documents, but it treats the vendored upstream grid files above as the design source of truth for report-layout enforcement.

Local adapter rules:

1. standalone HTML documents must stay aligned to a \`4px\` minimum spacing quantum
2. section-scale rhythm should prefer upstream-aligned macro values such as \`8px\`, \`16px\`, \`24px\`, and \`72px\`
3. deeply nested layout structures in standalone reports should be treated as a review smell
4. the repository hook may add extra safeguards that are not present upstream, such as nowrap prevention, status-chip stability, and CJK wrapping safety

## Enforcement Surface

The vendored upstream source above is enforced locally through:

- script: \`scripts/md8-design-hook.mjs\`
- command: \`npm run design:check\`
- build path: \`npm run build\`

Scope:

- \`doc/**/*.html\`
- \`outputs/reports/**/*.html\`

Non-scope:

- runtime React pages
- \`client/\` app shell
- non-HTML assets
`;
}

async function main() {
  const checkMode = process.argv.includes('--check');

  if (checkMode) {
    let existing;
    let lock;
    try {
      existing = await readFile(outputPath, 'utf8');
    } catch (error) {
      if (error && typeof error === 'object' && 'code' in error && error.code === 'ENOENT') {
        throw new Error(`design.md is missing. Run: npm run design:sync-source`);
      }
      throw error;
    }
    try {
      lock = JSON.parse(await readFile(lockPath, 'utf8'));
    } catch (error) {
      if (error && typeof error === 'object' && 'code' in error && error.code === 'ENOENT') {
        throw new Error(`design.source.lock.json is missing. Run: npm run design:sync-source`);
      }
      throw error;
    }
    validateLock(lock);
    if (sha256(existing) !== lock.document.sha256) {
      throw new Error(`design.md is out of sync with the pinned source lock. Run: npm run design:sync-source`);
    }
    console.log(`design.md matches pinned source lock`);
    return;
  }

  const fetched = await Promise.all(
    UPSTREAM.files.map(async (filePath) => ({
      filePath,
      url: rawUrl(filePath),
      content: await fetchText(rawUrl(filePath)),
    }))
  );

  const document = buildDocument(fetched);
  const lock = {
    upstream: UPSTREAM,
    document: {
      path: 'design.md',
      sha256: sha256(document),
    },
    files: fetched.map(({ filePath, url, content }) => ({
      path: filePath,
      url,
      sha256: sha256(content),
    })),
  };

  await writeFile(outputPath, document, 'utf8');
  await writeFile(lockPath, `${JSON.stringify(lock, null, 2)}\n`, 'utf8');
  console.log(`Synced design source to ${outputPath} and ${lockPath}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
